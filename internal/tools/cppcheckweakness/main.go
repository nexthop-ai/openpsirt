// Command cppcheckweakness writes the weakness each cppcheck check finds.
//
// cppcheck's SARIF names no weakness before it tags its rules with one:
// 2.16 to 2.18 tag a rule "security" and nothing else. Its XML names one per
// error, and so does its list of every check, which is what this reads. A
// rule whose tags name a weakness is classified by them, and this table
// answers only for one whose tags name none.
//
// Asked of cppcheck rather than typed, for the reason the weakness names are
// fetched: a few hundred pairs nobody checks by eye go wrong quietly. The
// version asked is recorded in the generated file, and the table is
// regenerated deliberately, by running this where cppcheck is installed.
//
//	make cppcheck-weaknesses
package main

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"sort"
	"strconv"
	"strings"
)

// written is where the table goes, relative to the repository root.
const written = "internal/weakness/cppcheck.go"

// errorList is the shape of `cppcheck --errorlist`, read down to each check's
// identifier and weakness.
type errorList struct {
	Version struct {
		Version string `xml:"version,attr"`
	} `xml:"cppcheck"`
	Errors []struct {
		ID  string `xml:"id,attr"`
		CWE string `xml:"cwe,attr"`
	} `xml:"errors>error"`
}

// checks is each check's weakness, from a list cppcheck wrote, and the
// version that wrote it. A check naming no weakness, or weakness zero, is
// left out.
func checks(list []byte) (string, map[string]string, error) {
	var doc errorList
	if err := xml.Unmarshal(list, &doc); err != nil { //nolint:gosec // G709: the list the cppcheck this was pointed at wrote
		return "", nil, fmt.Errorf("read the check list: %w", err)
	}
	version := strings.TrimSpace(doc.Version.Version)
	if version == "" {
		return "", nil, fmt.Errorf("the check list names no cppcheck version")
	}
	out := map[string]string{}
	for _, e := range doc.Errors {
		n, err := strconv.Atoi(strings.TrimSpace(e.CWE))
		if err != nil || n <= 0 || strings.TrimSpace(e.ID) == "" {
			continue
		}
		out[strings.TrimSpace(e.ID)] = "CWE-" + strconv.Itoa(n)
	}
	if len(out) == 0 {
		return "", nil, fmt.Errorf("the check list names no weakness, so this would write nothing")
	}
	return version, out, nil
}

// render is the generated file.
func render(version string, table map[string]string) ([]byte, error) {
	ids := make([]string, 0, len(table))
	for id := range table {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	var b bytes.Buffer
	b.WriteString("// Copyright Nexthop Systems Inc.\n// SPDX-License-Identifier: Apache-2.0\n\n")
	b.WriteString("// Code generated by internal/tools/cppcheckweakness. DO NOT EDIT.\n\n")
	b.WriteString("package weakness\n\n")
	b.WriteString("// cppcheckVersion is the cppcheck whose list of checks cppcheckChecks was\n// read from.\n")
	fmt.Fprintf(&b, "const cppcheckVersion = %q\n\n", version)
	b.WriteString("// cppcheckChecks is the weakness each cppcheck check finds, by its\n// identifier.\n")
	b.WriteString("var cppcheckChecks = map[string]string{\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%q: %q,\n", id, table[id])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func main() {
	tool := os.Getenv("CPPCHECK")
	if tool == "" {
		tool = "cppcheck"
	}
	list, err := exec.Command(tool, "--errorlist").Output() //nolint:gosec // G204: the cppcheck the person running this named
	if err != nil {
		fmt.Fprintf(os.Stderr, "run %s --errorlist: %v\n", tool, err)
		os.Exit(1)
	}
	version, table, err := checks(list)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	src, err := render(version, table)
	if err != nil {
		fmt.Fprintf(os.Stderr, "format %s: %v\n", written, err)
		os.Exit(1)
	}
	if err := os.WriteFile(written, src, 0o600); err != nil {
		fmt.Fprintf(os.Stderr, "write %s: %v\n", written, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %d checks from cppcheck %s to %s\n", len(table), version, written)
}
