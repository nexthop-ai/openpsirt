// everyEngine runs each against the three servers and a SQLite file of the
// test's own.
func everyEngine(t *testing.T, each func(t *testing.T, engine database.Engine, address string)) {
	t.Helper()
	servers(t, each)
	t.Run(string(database.SQLite), func(t *testing.T) {
		engines.SkipUnless(t, database.SQLite)
		each(t, database.SQLite, "sqlite://"+filepath.Join(t.TempDir(), "observed.db"))
	})
}

// changingWithin waits up to a few seconds for the observer to answer want,
// and fails the test naming what it last answered.
func changingWithin(t *testing.T, o *Observer, want bool, doing string) {
	t.Helper()
	deadline := time.Now().Add(10 * time.Second)
	for {
		change, err := o.changing(t.Context(), o.db, 0)
		got := change != Unchanged
		if err != nil {
			t.Fatalf("%s: asking whether the schema is changing: %v", doing, err)
		}
		if got == want {
			return
		}
		if time.Now().After(deadline) {
			t.Fatalf("%s: a serving instance saw the schema changing %v, not %v", doing, got, want)
		}
		time.Sleep(50 * time.Millisecond)
	}
}

// A serving instance sees, from another pool, a lease held to change the
// schema, and stops seeing it once the holder goes back to migrating or lets
// it go. A lease held to migrate alone is not seen, since a start with nothing
// to apply holds it.
func TestAServingInstanceSeesALeaseHeldToChangeTheSchema(t *testing.T) {
	everyEngine(t, func(t *testing.T, _ database.Engine, address string) {
		ctx := t.Context()
		migrating, serving := open(t, address), open(t, address)
		freshLease(t, migrating)
		observer, err := NewObserver(ctx, serving)
		if err != nil {
			t.Fatal(err)
		}
		changingWithin(t, observer, false, "before any lease")

		lock, err := acquire(ctx, migrating)
		if err != nil {
			t.Fatal(err)
		}
		defer func() { _ = lock.release(context.Background()) }()
		changingWithin(t, observer, false, "with the lease held to migrate")

		stopChanging, err := lock.change(ctx)
		if err != nil {
			t.Fatalf("hold the lease to change the schema: %v", err)
		}
		changingWithin(t, observer, true, "with the lease held to change the schema")

		if err := stopChanging(ctx); err != nil {
			t.Fatalf("hold the lease to migrate again: %v", err)
		}
		changingWithin(t, observer, false, "with the lease held to migrate again")

		if _, err := lock.change(ctx); err != nil {
			t.Fatalf("hold the lease to change the schema a second time: %v", err)
		}
		changingWithin(t, observer, true, "with the lease held to change the schema again")
		if err := lock.release(ctx); err != nil {
			t.Fatalf("let the lease go: %v", err)
		}
		changingWithin(t, observer, false, "after the lease was let go")
	})
}

// A lease held to change the schema by a process that died pauses serving
// instances until it lapses, and no longer: the schema it left is whole on
// PostgreSQL and SQLite, and on MySQL and MariaDB the record keeps them paused.
func TestServingInstancesResumeWhenALeaseHeldToChangeTheSchemaLapses(t *testing.T) {
	everyEngine(t, func(t *testing.T, _ database.Engine, address string) {
		ctx := t.Context()
		db, serving := open(t, address), open(t, address)
		freshLease(t, db)
		observer, err := NewObserver(ctx, serving)
		if err != nil {
			t.Fatal(err)
		}
		leftBy(t, db, holdingChange, 2*time.Second)
		changingWithin(t, observer, true, "before the lease lapsed")
		lapsed := time.Now().Add(2 * time.Second)
		changingWithin(t, observer, false, "after the lease lapsed")
		if early := time.Until(lapsed); early > 500*time.Millisecond {
			t.Errorf("a serving instance resumed %s before the lease lapsed", early)
		}
	})
}

// recordTable makes a record of schema changes shaped as a release's
// migration makes it, and drops it when the test ends.
func recordTable(t *testing.T, db *database.DB) {
	t.Helper()
	id := map[database.Engine]string{
		database.Postgres: "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
		database.MySQL:    "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY",
		database.MariaDB:  "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY",
		database.SQLite:   "INTEGER PRIMARY KEY",
	}[db.Server.Engine]
	drop := func() { _, _ = db.ExecContext(context.Background(), `DROP TABLE IF EXISTS "`+ChangeTable+`"`) }
	drop()
	if _, err := db.ExecContext(t.Context(), `CREATE TABLE "`+ChangeTable+`" ("id" `+id+`,
		"started_at" TIMESTAMP NULL, "started_by" VARCHAR(255) NOT NULL, "target_version" BIGINT NOT NULL)`); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(drop)
}

// versionTable makes the migration library's bookkeeping table, empty, and
// answers a function recording a version applied; it is dropped when the test
// ends.
func versionTable(t *testing.T, db *database.DB) func(version int64) {
	t.Helper()
	id := map[database.Engine]string{
		database.Postgres: "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
		database.MySQL:    "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY",
		database.MariaDB:  "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY",
		database.SQLite:   "INTEGER PRIMARY KEY",
	}[db.Server.Engine]
	drop := func() { _, _ = db.ExecContext(context.Background(), `DROP TABLE IF EXISTS "`+VersionTable+`"`) }
	drop()
	if _, err := db.ExecContext(t.Context(), `CREATE TABLE "`+VersionTable+`" ("id" `+id+`,
		"version_id" BIGINT NOT NULL, "is_applied" BOOLEAN NOT NULL, "tstamp" TIMESTAMP NULL)`); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(drop)
	return func(version int64) {
		t.Helper()
		if _, err := db.ExecContext(t.Context(), `INSERT INTO "`+VersionTable+`" ("version_id", "is_applied")
			VALUES (?, ?)`, version, true); err != nil {
			t.Fatal(err)
		}
	}
}

// An upgrade that fails leaves its record where the engine leaves the schema
// part changed, MySQL and MariaDB, so a serving instance stays paused once
// the lease is let go. Elsewhere no record is written before the first
// statement, and the lease alone says the schema is changing. A success
// clears the record on every engine.
func TestAFailedUpgradeKeepsServingInstancesPausedWhereItLeftThePartChanged(t *testing.T) {
	everyEngine(t, func(t *testing.T, engine database.Engine, address string) {
		ctx := t.Context()
		migrating, serving := open(t, address), open(t, address)
		freshLease(t, migrating)
		recordTable(t, migrating)
		applied := versionTable(t, migrating)
		applied(0)
		observer, err := NewObserver(ctx, serving)
		if err != nil {
			t.Fatal(err)
		}
		begin := func() func(error) {
			lock, err := acquire(ctx, migrating)
			if err != nil {
				t.Fatal(err)
			}
			end, err := beginChange(ctx, migrating, lock, slog.New(slog.DiscardHandler), 0, 1, 0)
			if err != nil {
				t.Fatal(err)
			}
			return func(failed error) {
				end(failed)
				_ = lock.release(ctx)
			}
		}

		end := begin()
		changingWithin(t, observer, true, "while the upgrade changes the schema")
		partChanged := engine == database.MySQL || engine == database.MariaDB
		// Elsewhere the transaction rolls back when the upgrade fails, a
		// killed process included, so a row would outlive a schema left whole.
		var rows int
		if err := migrating.QueryRowContext(ctx, `SELECT COUNT(*) FROM "`+ChangeTable+`"`).Scan(&rows); err != nil {
			t.Fatal(err)
		}
		if (rows > 0) != partChanged {
			t.Errorf("an upgrade under way wrote %d records; want one only where a failure leaves the schema part changed", rows)
		}
		end(errors.New("a statement failed"))
		changingWithin(t, observer, partChanged, "after the upgrade failed")

		end = begin()
		applied(1)
		end(nil)
		changingWithin(t, observer, false, "after an upgrade succeeded")
	})
}

// A look waits for a connection a busy pool frees rather than reading the
// wait as a change, and fails only once its bound on taking one passes.
func TestALookWaitsForABusyPool(t *testing.T) {
	engines.SkipUnless(t, database.SQLite)
	ctx := t.Context()
	db := open(t, "sqlite://"+filepath.Join(t.TempDir(), "busy.db"))
	if _, err := db.ExecContext(ctx, `CREATE TABLE "`+VersionTable+`" ("version_id" BIGINT, "is_applied" BOOLEAN)`); err != nil {
		t.Fatal(err)
	}
	if _, err := db.ExecContext(ctx, `INSERT INTO "`+VersionTable+`" VALUES (7, TRUE)`); err != nil {
		t.Fatal(err)
	}
	observer, err := NewObserver(ctx, db)
	if err != nil {
		t.Fatal(err)
	}
	db.SetMaxOpenConns(1)
	busy, err := db.DB.DB.Conn(ctx)
	if err != nil {
		t.Fatal(err)
	}
	if _, _, err := observer.Look(ctx, 100*time.Millisecond, time.Minute); err == nil {
		t.Fatal("a look answered with every connection held past its bound on taking one")
	}
	time.AfterFunc(300*time.Millisecond, func() { _ = busy.Close() })
	change, applied, err := observer.Look(ctx, time.Minute, 100*time.Millisecond)
	if err != nil || change != Unchanged || applied != 7 {
		t.Fatalf("a look past a pool busy for longer than its questions take: %v at %d, %v", change, applied, err)
	}
}

// No record of a change is written during the notice, so a process killed
// while it waits, with nothing changed, leaves none.
func TestNoRecordIsWrittenDuringTheNotice(t *testing.T) {
	everyEngine(t, func(t *testing.T, _ database.Engine, address string) {
		ctx := t.Context()
		migrating := open(t, address)
		freshLease(t, migrating)
		recordTable(t, migrating)
		lock, err := acquire(ctx, migrating)
		if err != nil {
			t.Fatal(err)
		}
		defer func() { _ = lock.release(context.Background()) }()
		waiting, stop := context.WithCancel(ctx)
		ended := make(chan error, 1)
		go func() {
			_, err := beginChange(waiting, migrating, lock, slog.New(slog.DiscardHandler), 1, 2, time.Minute)
			ended <- err
		}()
		time.Sleep(500 * time.Millisecond)
		var rows int
		if err := migrating.QueryRowContext(ctx, `SELECT COUNT(*) FROM "`+ChangeTable+`"`).Scan(&rows); err != nil {
			t.Fatal(err)
		}
		if rows != 0 {
			t.Errorf("%d records were written during the notice", rows)
		}
		stop()
		if err := <-ended; err == nil {
			t.Error("an upgrade stopped during the notice reported going on")
		}
	})
}
